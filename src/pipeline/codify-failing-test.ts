/**
 * Deterministically turns the recorded actions + expected assertion into a
 * Playwright spec. No LLM writes test code: the spec is exactly the actions
 * the agent performed, so it is reviewable and reproducible.
 * Returns the source and the line range of the assertion block, which lets
 * the runner tell "failed on the bug" from "failed while reproducing".
 */
import { actionCode, locatorCode, type ScopedLocator, type SpecAction } from '../lib/spec-actions.js';
import type { TargetApp } from '../targets/target-apps.js';
import type { ExpectedAssertion } from './propose-expected-assertion.js';

export type CodifiedSpec = { source: string; assertLines: [number, number] };

const q = (s: unknown) => JSON.stringify(s);

function expectCode(a: ExpectedAssertion): string {
  const all = locatorCode(a.locator as ScopedLocator);
  // Assert on the first VISIBLE match: apps often render hidden duplicates (e.g. mobile labels).
  const loc = `${all}.filter({ visible: true })`;
  switch (a.check) {
    case 'toBeVisible':
      return `await expect(${loc}.first()).toBeVisible();`;
    case 'toHaveText':
      return `await expect(${loc}.first()).toHaveText(${q(String(a.value ?? ''))});`;
    case 'toContainText':
      return `await expect(${loc}.first()).toContainText(${q(String(a.value ?? ''))});`;
    case 'toHaveCount':
      return `await expect(${all}).toHaveCount(${Number(a.value ?? 0)});`;
    case 'toBeChecked':
      return `await expect(${loc}.first()).toBeChecked();`;
    case 'changesAfterAction':
      return `await expect(${loc}.first()).not.toHaveText(before);`;
  }
}

export function codifyFailingTest(app: TargetApp, title: string, expected: string, actions: SpecAction[], assertion: ExpectedAssertion): CodifiedSpec {
  const capture = assertion.check === 'changesAfterAction' ? (assertion.captureBeforeAction ?? 0) : -1;
  const captureLine = `before = (await ${locatorCode(assertion.locator as ScopedLocator)}.first().innerText()).trim();`;
  const body = actions.flatMap((a, i) => (i === capture ? [captureLine, actionCode(a)] : [actionCode(a)]));
  if (capture >= actions.length) body.push(captureLine);

  const head = [
    `// Generated by Bug2PR: reproduces a bug from a screen recording.`,
    `// Expected behaviour: ${expected.replace(/\n/g, ' ')}`,
    `import { expect, test } from '@playwright/test';`,
    ``,
    `test(${q(title)}, async ({ page }) => {`,
    `  let before = '';`,
    `  await page.setViewportSize(${q(app.viewport)});`,
    `  await test.step('reproduce', async () => {`,
    ...[`await page.goto(${q(app.url)});`, ...app.setup.map(actionCode), ...body].map((l) => `    ${l}`),
    `  });`,
    `  await test.step(${q(`expected: ${assertion.description}`)}, async () => {`,
  ];
  const assertStart = head.length + 1; // 1-based line of the expect call
  const lines = [...head, `    ${expectCode(assertion)}`, `  });`, `  void before;`, `});`, ``];
  return { source: lines.join('\n'), assertLines: [assertStart, assertStart] };
}
