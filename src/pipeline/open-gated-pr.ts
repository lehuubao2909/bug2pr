/**
 * Final gate: packages a verified fix as a pull request.
 * Locally it creates branch bug2pr/<id> with the fix plus the regression
 * test (rewritten to the repo's own base URL) and writes the PR description
 * with all evidence. Pushing and opening the PR is a separate, explicit step
 * (pushPullRequest) that only runs after a person signs off.
 */
import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { TargetApp } from '../targets/target-apps.js';
import type { FixResult } from './fix-loop.js';
import type { Repro } from './repro-steps-schema.js';

const MAX_CHANGED_LINES = 120; // larger fixes need a human from the start

export type PrDraft = { status: 'awaiting-sign-off' | 'escalated'; reason: string; branch?: string; commit?: string; title?: string; bodyFile?: string };

const git = (dir: string, ...args: string[]) => execFileSync('git', ['-C', dir, ...args], { stdio: 'pipe' }).toString().trim();

/** Rewrites absolute dev-server URLs in the spec to paths, so the repo's config decides the host. */
function toRepoTest(specSource: string, appUrl: string): string {
  const origin = new URL(appUrl).origin;
  return specSource.split(`"${origin}`).join('"');
}

function prBody(bugId: string, repro: Repro, fix: FixResult, testPath: string, evidence: { failsBefore: string; replayTurns: number; video: string }): string {
  const last = fix.attempts.at(-1)!;
  const steps = repro.steps.map((s, i) => `${i + 1}. \`${s.t}\` ${s.action} **${s.target}**${s.value ? ` → \`${s.value}\`` : ''}`).join('\n');
  const checks = last.checks.map((c) => `| \`${c.command}\` | ✅ | ${(c.ms / 1000).toFixed(1)}s |`).join('\n');
  return `## Summary
${fix.rootCause}

## Bug (from screen recording \`${evidence.video}\`)
**Expected:** ${repro.expected}
**Actual:** ${repro.actual}

### Steps extracted from the video
${steps}

## Verification
| Check | Result | Time |
|---|---|---|
| Regression test \`${testPath}\` fails on the buggy code at the expected-behaviour assertion | ✅ ${evidence.failsBefore} runs | |
| Same test passes with this fix | ✅ | |
${checks}

Fix accepted on attempt ${fix.attempts.length}. The bug was first reproduced live by a computer-use agent in ${evidence.replayTurns} turns.

---
Generated by **Bug2PR** for \`${bugId}\` (Muse Spark 1.3 video understanding + computer use, SAM 3.1 cursor grounding, Muse Wonder fix). Please review before merging.`;
}

export async function prepareGatedPr(
  app: TargetApp,
  bugId: string,
  repro: Repro,
  fix: FixResult,
  specFile: string,
  evidence: { failsBefore: string; replayTurns: number; video: string },
): Promise<PrDraft> {
  if (fix.status !== 'fixed' || !fix.diff) return { status: 'escalated', reason: 'no verified fix' };
  const changed = fix.diff.split('\n').filter((l) => /^[+-][^+-]/.test(l)).length;
  if (changed > MAX_CHANGED_LINES) return { status: 'escalated', reason: `fix changes ${changed} lines (> ${MAX_CHANGED_LINES}); needs human review first` };

  const testPath = app.testFile(bugId);
  await mkdir(path.dirname(path.join(app.repoDir, testPath)), { recursive: true });
  await writeFile(path.join(app.repoDir, testPath), toRepoTest(await readFile(specFile, 'utf8'), app.url));

  const branch = `bug2pr/${bugId}`;
  const title = fix.title ?? 'fix: bug reproduced from screen recording';
  git(app.repoDir, 'checkout', '-q', '-B', branch);
  git(app.repoDir, 'add', '-A');
  git(app.repoDir, 'commit', '-q', '-m', title, '-m', `Reproduced from a screen recording and verified by a regression test (${testPath}).`);
  const commit = git(app.repoDir, 'rev-parse', '--short', 'HEAD');

  const outDir = path.resolve('runs/pr', bugId);
  await mkdir(outDir, { recursive: true });
  const bodyFile = path.join(outDir, 'PR.md');
  await writeFile(bodyFile, `# ${title}\n\n${prBody(bugId, repro, fix, testPath, evidence)}\n`);
  await writeFile(path.join(outDir, 'fix.diff'), fix.diff);
  return { status: 'awaiting-sign-off', reason: 'verified fix committed locally; push needs human sign-off', branch, commit, title, bodyFile };
}

/** Pushes the branch and opens the PR. Call ONLY after a person approved the draft. */
export async function pushPullRequest(app: TargetApp, draft: PrDraft, remote: string, repo: string): Promise<string> {
  if (draft.status !== 'awaiting-sign-off' || !draft.branch || !draft.bodyFile || !draft.title) throw new Error('PR draft is not ready');
  git(app.repoDir, 'push', '-u', remote, draft.branch);
  return execFileSync('gh', ['pr', 'create', '--repo', repo, '--head', draft.branch, '--title', draft.title, '--body-file', draft.bodyFile], { cwd: app.repoDir }).toString().trim();
}
