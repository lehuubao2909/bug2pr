/**
 * Builds docs/eval-results.md from the latest eval runs, so README numbers
 * always come from real run artifacts:
 *   runs/eval-extraction/summary.json   (phase 3: video -> steps)
 *   runs/eval-replay/summary.json       (phase 4: replay -> gated failing test)
 *   runs/eval-fix-{meta,baseten}/...    (phase 5: fix loop per provider)
 *
 * Usage: npm run eval:summary
 */
import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

type Row = Record<string, unknown>;
const load = async <T>(file: string): Promise<T | undefined> => (existsSync(file) ? (JSON.parse(await readFile(file, 'utf8')) as T) : undefined);
const cell = (v: unknown) => (v === true ? '✅' : v === false ? '❌' : v === undefined || v === null ? '–' : String(v));
const table = (headers: string[], rows: unknown[][]) =>
  [`| ${headers.join(' | ')} |`, `|${headers.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');

async function main(): Promise<void> {
  const extraction = await load<{ summary: Row[] }>('runs/eval-extraction/summary.json');
  const replay = await load<Row[]>('runs/eval-replay/summary.json');
  const fixMeta = (await load<Row[]>('runs/eval-fix-meta/summary.json')) ?? (await load<Row[]>('runs/eval-fix/summary.json'));
  const fixOpen = await load<Row[]>('runs/eval-fix-baseten/summary.json');

  const parts = [
    '# Bug2PR evaluation results',
    '',
    'Generated by `npm run eval:summary` from run artifacts in `runs/`. Eval set: 3 seeded bugs in shadcn-admin + 1 real bug in Actual Budget ([#8475](https://github.com/actualbudget/actual/issues/8475)). Small sample: treat as indicative, not a benchmark.',
    '',
    '## 1. Video → repro steps (Muse Spark 1.3, with/without SAM 3.1 cursor grounding)',
    'LLM judge (Muse Spark) compares predicted steps and diagnosis to `truth.json`.',
    '',
    extraction ? table(['Mode', 'Runs', 'Step recall', 'Invented steps / run', 'Diagnosis correct'], extraction.summary.map((s) => [s.mode, s.runs, s.stepRecall, s.extraStepsPerRun, s.diagnosisAccuracy])) : '_not run_',
    '',
    '## 2. Live reproduction (computer use) → gated failing test',
    'Gate: test must fail at the expected-behaviour assertion 3/3 times, its locator must exist, and it must be sensitive to the repro steps. "Passes on fix" is an eval-only check against the known fix.',
    '',
    replay ? table(['Bug', 'Result', 'Agent reproduced', 'Turns', 'Replay (s)', 'Fails on bug', 'Passes on fix'], replay.map((r) => [r.id, r.status, r.reproducedByAgent, r.turns, r.replaySec, r.failsOnBug, r.passesOnFix])) : '_not run_',
    '',
    '## 3. Fix loop → verified local PR',
    'A fix is accepted only if the generated test passes and the repo\'s own checks stay green. "Independent truth" = our gold spec (seeded bugs) or the upstream PR\'s own e2e test (real bug).',
    '',
  ];
  for (const [label, rows] of [['Muse Wonder 1.0 (Meta Model API)', fixMeta], ['Muse Spark Open (open weights via Baseten)', fixOpen]] as const) {
    parts.push(`### ${label}`, '');
    parts.push(rows ? table(['Bug', 'Result', 'Right file found', 'Attempts', 'Independent truth passes', 'Total (s)', 'Changed lines'], rows.map((r) => [r.id, r.status, r.localizedHit, r.attempts, r.groundTruthPasses, r.fixSec, r.changedLines])) : '_not run_', '');
  }
  await mkdir('docs', { recursive: true });
  await writeFile('docs/eval-results.md', parts.join('\n'));
  console.log('Wrote docs/eval-results.md');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
